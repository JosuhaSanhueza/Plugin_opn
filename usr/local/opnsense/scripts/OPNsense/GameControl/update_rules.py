#!/usr/bin/env python3
import os
import json
import datetime
import urllib.request
import re
import xml.etree.ElementTree as ET

CONFIG_PATH = '/conf/config.xml'
UNBLOCKED_FILE = '/var/etc/gamecontrol_unblocked.json'
LOG_FILE = '/var/log/gamecontrol.log'
GAMECONTROL_CONF = '/var/unbound/etc/gamecontrol.conf'
DEFAULT_URL = "https://raw.githubusercontent.com/JosuhaSanhueza/BlockList/refs/heads/main/GamesBlockList.txt"

def log_msg(msg):
    timestamp = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    formatted = f"[{timestamp}] {msg}\n"
    print(formatted.strip())
    try:
        with open(LOG_FILE, 'a') as f:
            f.write(formatted)
    except Exception:
        pass

def parse_hosts_from_github(url):
    domains = set()
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'OPNsense-GameControl'})
        with urllib.request.urlopen(req, timeout=10) as response:
            content = response.read().decode('utf-8')
            for line in content.splitlines():
                line = line.strip()
                if not line or line.startswith('#') or line.startswith('!'):
                    continue
                parts = line.split()
                domain = parts[1] if len(parts) >= 2 else parts[0]
                domain = domain.lstrip('|').rstrip('^').strip()
                if domain and domain != 'localhost' and '.' in domain:
                    domains.add(domain)
    except Exception as e:
        log_msg(f"Error descargando lista desde {url}: {e}")
    return domains

def update_game_control():
    log_msg("Iniciando actualización nativa de Unbound GameControl...")

    # 1. Obtener dominios de juegos
    domains = parse_hosts_from_github(DEFAULT_URL)
    log_msg(f"Se obtuvieron {len(domains)} dominios de juegos desde GitHub")

    # 2. Obtener IPs desbloqueadas (Permitidas)
    unblocked_ips = set()
    if os.path.exists(UNBLOCKED_FILE):
        try:
            with open(UNBLOCKED_FILE, 'r') as f:
                data = json.load(f)
                if isinstance(data, dict):
                    for ip, st in data.items():
                        if st == 0:
                            unblocked_ips.add(ip)
                elif isinstance(data, list):
                    for ip in data:
                        unblocked_ips.add(str(ip))
        except Exception as e:
            log_msg(f"Error leyendo {UNBLOCKED_FILE}: {e}")

    # 3. Generar lista de IPs a las que se les aplicará el bloqueo
    blocked_ips = []
    for i in range(101, 146):
        ip_addr = f"192.168.12.{i}"
        if ip_addr not in unblocked_ips:
            blocked_ips.append(ip_addr)

    log_msg(f"IPs con bloqueo de juegos activo: {len(blocked_ips)} (Permitidas: {len(unblocked_ips)})")

    # 4. Escribir configuración nativa de Unbound por Tagging
    lines = [
        "# Auto-generated by OPNsense GameControl Plugin",
        "server:",
        '    define-tag: "gaming_blocked"',
        '    access-control-tag-action: "gaming_blocked" always_refuse'
    ]

    for ip in blocked_ips:
        lines.append(f'    access-control-tag: {ip}/32 "gaming_blocked"')

    for domain in domains:
        lines.append(f'    local-zone: "{domain}" refuse')
        lines.append(f'    access-control-tag-data: "{domain}" "gaming_blocked" always_refuse')

    os.makedirs(os.path.dirname(GAMECONTROL_CONF), exist_ok=True)
    with open(GAMECONTROL_CONF, 'w') as f:
        f.write("\n".join(lines) + "\n")

    # 5. Asegurar include en /var/unbound/unbound.conf
    unbound_conf = '/var/unbound/unbound.conf'
    include_line = f'include: {GAMECONTROL_CONF}'
    if os.path.exists(unbound_conf):
        try:
            with open(unbound_conf, 'r') as f:
                ucontent = f.read()
            if include_line not in ucontent:
                with open(unbound_conf, 'a') as f:
                    f.write(f"\n{include_line}\n")
                log_msg(f"Se insertó '{include_line}' en {unbound_conf}")
        except Exception as e:
            log_msg(f"Error actualizando {unbound_conf}: {e}")

    # 6. Recargar Unbound en caliente (RAM)
    os.system('/usr/local/sbin/unbound-control reload >/dev/null 2>&1 || /usr/local/sbin/pluginctl -s unbound restart >/dev/null 2>&1')
    log_msg("Sincronización nativa de Unbound ejecutada exitosamente.")

if __name__ == '__main__':
    update_game_control()





