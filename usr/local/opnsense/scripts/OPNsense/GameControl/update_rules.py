#!/usr/bin/env python3
import os, json, datetime, urllib.request, urllib.parse, re

UNBLOCKED_FILE = "/var/etc/gamecontrol_unblocked.json"
LOG_FILE = "/var/log/gamecontrol.log"
ADGUARD_API_URL = "http://127.0.0.1:3000/control"
LOCAL_CACHE_GAMES = "/var/etc/gamecontrol_domains_cache.json"

def log_msg(msg):
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    formatted = "[" + timestamp + "] " + str(msg) + "\n"
    print(formatted.strip())
    try:
        with open(LOG_FILE, "a") as f:
            f.write(formatted)
    except Exception:
        pass

def get_games_domains_from_exact_filter():
    domains = set()
    for base_dir in ["/usr/local/bin", "/var/db/adguardhome", "/var/adguardhome", "/usr/local/etc/adguardhome"]:
        filters_dir = os.path.join(base_dir, "data", "filters")
        if os.path.exists(filters_dir):
            try:
                for root, dirs, files in os.walk(filters_dir):
                    for file in files:
                        if file.endswith(".txt"):
                            fpath = os.path.join(root, file)
                            with open(fpath, "r", encoding="utf-8", errors="ignore") as f:
                                lines = f.readlines()
                                content_head = "".join(lines[:30])
                                if len(lines) < 2000 and ("1001juegos.com" in content_head or "crazygames.com" in content_head or "GamesBlockList" in content_head):
                                    for line in lines:
                                        line = line.strip()
                                        if not line or line.startswith("#") or line.startswith("!") or line.startswith("<") or line.startswith("="):
                                            continue
                                        parts = line.split()
                                        domain = parts[1] if len(parts) >= 2 else parts[0]
                                        domain = domain.lstrip("|").rstrip("^").strip()
                                        if domain and domain != "localhost" and "." in domain and not domain.startswith("_"):
                                            domains.add(domain)
                                    log_msg("Leidos exactamente " + str(len(domains)) + " dominios de juegos desde el filtro de AdGuard (" + fpath + ")")
                                    return sorted(list(domains))
            except Exception:
                pass
    if os.path.exists(LOCAL_CACHE_GAMES):
        try:
            with open(LOCAL_CACHE_GAMES, "r") as f:
                cached = json.load(f)
                if isinstance(cached, list):
                    domains = set(cached)
                    log_msg("Leidos " + str(len(domains)) + " dominios desde cache local")
                    return sorted(list(domains))
        except Exception:
            pass
    return sorted(list(domains))

def update_game_control():
    log_msg("Sincronizando sintaxis oficial de pipe ($client=IP1|IP2) para AdGuard Home...")
    domains = get_games_domains_from_exact_filter()
    log_msg("Total dominios de la lista Games: " + str(len(domains)))

    unblocked_ips = set()
    if os.path.exists(UNBLOCKED_FILE):
        try:
            with open(UNBLOCKED_FILE, "r") as f:
                data = json.load(f)
                if isinstance(data, dict):
                    for ip, st in data.items():
                        if st == 0:
                            unblocked_ips.add(ip)
                elif isinstance(data, list):
                    for ip in data:
                        unblocked_ips.add(str(ip))
        except Exception as e:
            log_msg("Error leyendo unblocked file: " + str(e))

    log_msg("IPs de Alumnos con juegos permitidos: " + str(len(unblocked_ips)))

    user_rules = ["! Auto-generated by OPNsense Escolarapp Game Manager"]
    if unblocked_ips and domains:
        clients_pipe_param = "|".join(sorted(list(unblocked_ips)))
        for domain in domains:
            user_rules.append("@@||" + domain + "^$client=" + clients_pipe_param)
            user_rules.append("@@||*." + domain + "^$client=" + clients_pipe_param)

    log_msg("Generando exactamente " + str(len(user_rules)) + " lineas fijas ultracompactas con pipe |")

    rules_written = False
    try:
        rules_text = "\n".join(user_rules)
        req = urllib.request.Request(
            ADGUARD_API_URL + "/filtering/set_rules",
            data=json.dumps({"rules": rules_text}).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=5) as resp:
            rules_written = True
            log_msg("Excepciones ultracompactas con pipe | (" + str(len(user_rules)) + " lineas) sincronizadas via API.")
    except Exception:
        pass

    if not rules_written:
        for yaml_path in ["/usr/local/bin/AdGuardHome.yaml", "/var/db/adguardhome/AdGuardHome.yaml", "/usr/local/etc/adguardhome/AdGuardHome.yaml", "/var/adguardhome/AdGuardHome.yaml"]:
            if os.path.exists(yaml_path):
                try:
                    with open(yaml_path, "r") as f:
                        lines = f.readlines()
                    new_lines = []
                    in_user_rules = False
                    for line in lines:
                        if line.strip().startswith("user_rules:"):
                            in_user_rules = True
                            new_lines.append("user_rules:\n")
                            for r in user_rules:
                                new_lines.append("  - \"" + r + "\"\n")
                            continue
                        if in_user_rules:
                            if line.startswith("  - ") or line.startswith("    "):
                                continue
                            else:
                                in_user_rules = False
                        new_lines.append(line)
                    with open(yaml_path, "w") as f:
                        f.writelines(new_lines)
                    log_msg("Excepciones con pipe | (" + str(len(user_rules)) + " lineas) escritas en " + yaml_path + ". Recargando AdGuard en segundo plano...")
                    os.system("(/usr/local/bin/AdGuardHome -s reload || /usr/local/bin/AdGuardHome -s restart || service adguardhome restart) >/dev/null 2>&1 &")
                    rules_written = True
                    break
                except Exception as ex:
                    log_msg("Error escribiendo reglas en " + yaml_path + ": " + str(ex))

if __name__ == "__main__":
    update_game_control()
