#!/usr/bin/env python3
import os, json, datetime, urllib.request, urllib.parse, re

UNBLOCKED_FILE = "/var/etc/gamecontrol_unblocked.json"
LOG_FILE = "/var/log/gamecontrol.log"
ADGUARD_API_URL = "http://127.0.0.1:3000/control"

def log_msg(msg):
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    formatted = "[" + timestamp + "] " + str(msg) + "\n"
    print(formatted.strip())
    try:
        with open(LOG_FILE, "a") as f:
            f.write(formatted)
    except Exception:
        pass

def update_game_control():
    log_msg("Sincronizando clientes persistentes en AdGuard Home (Boton Verde = Sin filtros, Boton Rojo = Con filtros globales)...")

    unblocked_ips = set()
    if os.path.exists(UNBLOCKED_FILE):
        try:
            with open(UNBLOCKED_FILE, "r") as f:
                data = json.load(f)
                if isinstance(data, dict):
                    for ip, st in data.items():
                        if st == 0:
                            unblocked_ips.add(ip)
                elif isinstance(data, list):
                    for ip in data:
                        unblocked_ips.add(str(ip))
        except Exception as e:
            log_msg("Error leyendo unblocked file: " + str(e))

    log_msg("IPs de Alumnos con juegos habilitados: " + str(len(unblocked_ips)))

    # Configurar Clientes Persistentes en AdGuard Home via API o AdGuardHome.yaml
    clients_list = []
    for i in range(101, 146):
        ip_addr = "192.168.12." + str(i)
        hostname = "Lab2-" + str(i - 100)
        is_allowed = ip_addr in unblocked_ips
        client_obj = {
            "name": hostname,
            "ids": [ip_addr],
            "use_global_settings": False,
            "filtering_enabled": not is_allowed,
            "parental_enabled": False,
            "safesearch_enabled": False,
            "use_global_blocked_services": True,
            "blocked_services": []
        }
        clients_list.append(client_obj)
        try:
            req = urllib.request.Request(
                ADGUARD_API_URL + "/clients/update",
                data=json.dumps(client_obj).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST"
            )
            with urllib.request.urlopen(req, timeout=2) as resp:
                pass
        except Exception:
            try:
                req_add = urllib.request.Request(
                    ADGUARD_API_URL + "/clients/add",
                    data=json.dumps(client_obj).encode("utf-8"),
                    headers={"Content-Type": "application/json"},
                    method="POST"
                )
                with urllib.request.urlopen(req_add, timeout=2) as resp:
                    pass
            except Exception:
                pass

    # Limpiar user_rules ya que no es necesario inyectar lineas
    user_rules = ["! Auto-generated by OPNsense Escolarapp Game Manager"]
    rules_written = False
    try:
        req = urllib.request.Request(
            ADGUARD_API_URL + "/filtering/set_rules",
            data=json.dumps({"rules": "\n".join(user_rules)}).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=3) as resp:
            rules_written = True
    except Exception:
        pass

    if not rules_written:
        for yaml_path in ["/usr/local/bin/AdGuardHome.yaml", "/var/db/adguardhome/AdGuardHome.yaml", "/usr/local/etc/adguardhome/AdGuardHome.yaml", "/var/adguardhome/AdGuardHome.yaml"]:
            if os.path.exists(yaml_path):
                try:
                    with open(yaml_path, "r") as f:
                        content = f.read()
                    formatted_rules = "user_rules:\n  - \"! Auto-generated by OPNsense Escolarapp Game Manager\"\n"
                    if "user_rules:" in content:
                        new_content = re.sub(r"user_rules:.*?(?=\n\w|\Z)", formatted_rules.strip(), content, flags=re.DOTALL)
                    else:
                        new_content = content + "\n" + formatted_rules
                    with open(yaml_path, "w") as f:
                        f.write(new_content)
                    log_msg("Estado de clientes sincronizado en " + yaml_path + ". Recargando AdGuard...")
                    os.system("/usr/local/bin/AdGuardHome -s restart >/dev/null 2>&1 || service adguardhome restart >/dev/null 2>&1 || pkill -HUP AdGuardHome >/dev/null 2>&1")
                    break
                except Exception as ex:
                    log_msg("Error escribiendo en " + yaml_path + ": " + str(ex))

if __name__ == "__main__":
    update_game_control()
