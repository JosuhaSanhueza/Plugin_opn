#!/usr/bin/env python3
import os, json, datetime, urllib.request, urllib.parse, re

UNBLOCKED_FILE = "/var/etc/gamecontrol_unblocked.json"
LOG_FILE = "/var/log/gamecontrol.log"
ADGUARD_API_URL = "http://127.0.0.1:3000/control"
GITHUB_GAMES_URL = "https://raw.githubusercontent.com/JosuhaSanhueza/BlockList/refs/heads/main/GamesBlockList.txt"
LOCAL_CACHE_GAMES = "/var/etc/gamecontrol_domains_cache.json"

def log_msg(msg):
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    formatted = "[" + timestamp + "] " + str(msg) + "\n"
    print(formatted.strip())
    try:
        with open(LOG_FILE, "a") as f:
            f.write(formatted)
    except Exception:
        pass

def parse_hosts_from_github(url):
    domains = set()
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "OPNsense-GameControl"})
        with urllib.request.urlopen(req, timeout=10) as response:
            content = response.read().decode("utf-8")
            for line in content.splitlines():
                line = line.strip()
                if not line or line.startswith("#") or line.startswith("!") or line.startswith("<") or line.startswith("="):
                    continue
                parts = line.split()
                domain = parts[1] if len(parts) >= 2 else parts[0]
                domain = domain.lstrip("|").rstrip("^").strip()
                if domain and domain != "localhost" and "." in domain and not domain.startswith("_"):
                    domains.add(domain)
        if domains:
            try:
                with open(LOCAL_CACHE_GAMES, "w") as f:
                    json.dump(list(domains), f)
            except Exception:
                pass
    except Exception as e:
        log_msg("Advertencia descargando lista desde GitHub. Cargando cache local...")
        if os.path.exists(LOCAL_CACHE_GAMES):
            try:
                with open(LOCAL_CACHE_GAMES, "r") as f:
                    cached = json.load(f)
                    if isinstance(cached, list):
                        domains = set(cached)
            except Exception:
                pass
    return sorted(list(domains))

def update_game_control():
    log_msg("Sincronizando exenciones ultracompactas (IPs concatenadas por coma) para AdGuard Home...")
    domains = parse_hosts_from_github(GITHUB_GAMES_URL)
    log_msg("Se obtuvieron " + str(len(domains)) + " dominios de juegos de GitHub")

    unblocked_ips = set()
    if os.path.exists(UNBLOCKED_FILE):
        try:
            with open(UNBLOCKED_FILE, "r") as f:
                data = json.load(f)
                if isinstance(data, dict):
                    for ip, st in data.items():
                        if st == 0:
                            unblocked_ips.add(ip)
                elif isinstance(data, list):
                    for ip in data:
                        unblocked_ips.add(str(ip))
        except Exception as e:
            log_msg("Error leyendo unblocked file: " + str(e))

    log_msg("IPs de Alumnos con juegos permitidos: " + str(len(unblocked_ips)))

    user_rules = ["! Auto-generated by OPNsense Escolarapp Game Manager"]
    if unblocked_ips:
        clients_param = ",".join(sorted(list(unblocked_ips)))
        for domain in domains:
            user_rules.append("@@||" + domain + "^$client=" + clients_param)
            user_rules.append("@@||*." + domain + "^$client=" + clients_param)

    log_msg("Generando un total de " + str(len(user_rules)) + " lineas de exencion en AdGuard Home")

    rules_written = False
    try:
        rules_text = "\n".join(user_rules)
        req = urllib.request.Request(
            ADGUARD_API_URL + "/filtering/set_rules",
            data=json.dumps({"rules": rules_text}).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=5) as resp:
            rules_written = True
            log_msg("Excepciones ultracompactas (" + str(len(user_rules)) + " lineas) sincronizadas via API.")
    except Exception:
        pass

    if not rules_written:
        for yaml_path in ["/usr/local/bin/AdGuardHome.yaml", "/var/db/adguardhome/AdGuardHome.yaml", "/usr/local/etc/adguardhome/AdGuardHome.yaml", "/var/adguardhome/AdGuardHome.yaml"]:
            if os.path.exists(yaml_path):
                try:
                    with open(yaml_path, "r") as f:
                        lines = f.readlines()
                    new_lines = []
                    in_user_rules = False
                    for line in lines:
                        if line.strip().startswith("user_rules:"):
                            in_user_rules = True
                            new_lines.append("user_rules:\n")
                            for r in user_rules:
                                new_lines.append("  - \"" + r + "\"\n")
                            continue
                        if in_user_rules:
                            if line.startswith("  - ") or line.startswith("    "):
                                continue
                            else:
                                in_user_rules = False
                        new_lines.append(line)
                    with open(yaml_path, "w") as f:
                        f.writelines(new_lines)
                    log_msg("Excepciones (" + str(len(user_rules)) + " lineas) escritas en " + yaml_path + ". Recargando AdGuard...")
                    os.system("/usr/local/bin/AdGuardHome -s restart >/dev/null 2>&1 || service adguardhome restart >/dev/null 2>&1 || pkill -HUP AdGuardHome >/dev/null 2>&1")
                    rules_written = True
                    break
                except Exception as ex:
                    log_msg("Error escribiendo reglas en " + yaml_path + ": " + str(ex))

if __name__ == "__main__":
    update_game_control()
