#!/usr/bin/env python3
import os
import json
import datetime
import urllib.request
import urllib.parse

UNBLOCKED_FILE = '/var/etc/gamecontrol_unblocked.json'
LOG_FILE = '/var/log/gamecontrol.log'
ADGUARD_API_URL = 'http://127.0.0.1:3000/control'
GITHUB_GAMES_URL = "https://raw.githubusercontent.com/JosuhaSanhueza/BlockList/refs/heads/main/GamesBlockList.txt"
LOCAL_CACHE_GAMES = '/var/etc/gamecontrol_domains_cache.json'
DEFAULT_FALLBACK_DOMAINS = [
    "poki.com", "api.poki.com", "a.poki-cdn.com", "img.poki-cdn.com",
    "stumbleguys.com", "roblox.com", "rbxcdn.com", "friv.com",
    "y8.com", "crazygames.com", "kizi.com", "poki.es", "browsergames.com"
]

def log_msg(msg):
    timestamp = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    formatted = f"[{timestamp}] {msg}\n"
    print(formatted.strip())
    try:
        with open(LOG_FILE, 'a') as f:
            f.write(formatted)
    except Exception:
        pass


def parse_hosts_from_github(url):
    domains = set()
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'OPNsense-GameControl'})
        with urllib.request.urlopen(req, timeout=10) as response:
            content = response.read().decode('utf-8')
            for line in content.splitlines():
                line = line.strip()
                if not line or line.startswith('#') or line.startswith('!'):
                    continue
                parts = line.split()
                domain = parts[1] if len(parts) >= 2 else parts[0]
                domain = domain.lstrip('|').rstrip('^').strip()
                if domain and domain != 'localhost' and '.' in domain:
                    domains.add(domain)
        if domains:
            try:
                with open(LOCAL_CACHE_GAMES, 'w') as f:
                    json.dump(list(domains), f)
            except Exception:
                pass
    except Exception as e:
        log_msg(f"Advertencia descargando lista desde GitHub ({e}). Intentando cargar desde caché local...")
        if os.path.exists(LOCAL_CACHE_GAMES):
            try:
                with open(LOCAL_CACHE_GAMES, 'r') as f:
                    cached = json.load(f)
                    if isinstance(cached, list):
                        domains = set(cached)
            except Exception:
                pass
        if not domains:
            domains = set(DEFAULT_FALLBACK_DOMAINS)
    return sorted(list(domains))


def update_game_control():
    log_msg("Iniciando sincronización con AdGuard Home API...")

    # 1. Cargar dominios de la lista de juegos de GitHub
    domains = parse_hosts_from_github(GITHUB_GAMES_URL)
    log_msg(f"Se obtuvieron {len(domains)} dominios de juegos para AdGuard Home")

    # 2. Leer IPs permitidas desde la web
    unblocked_ips = set()
    if os.path.exists(UNBLOCKED_FILE):
        try:
            with open(UNBLOCKED_FILE, 'r') as f:
                data = json.load(f)
                if isinstance(data, dict):
                    for ip, st in data.items():
                        if st == 0:
                            unblocked_ips.add(ip)
                elif isinstance(data, list):
                    for ip in data:
                        unblocked_ips.add(str(ip))
        except Exception as e:
            log_msg(f"Error leyendo {UNBLOCKED_FILE}: {e}")

    log_msg(f"IPs con juegos permitidos: {len(unblocked_ips)}")

    # 3. Configurar reglas de filtrado por cliente (Rules) en AdGuard Home
    # Generar reglas Adblock ($client) para bloquear los juegos únicamente en las IPs bloqueadas
    user_rules = ["! Auto-generated by OPNsense Escolarapp Game Manager"]
    
    # Agregar dominios a la lista de reglas filtradas por IP de cliente
    for i in range(101, 146):
        ip_addr = f"192.168.12.{i}"
        is_allowed = ip_addr in unblocked_ips
        
        # Si el alumno está bloqueado (botón rojo), agregar sus reglas de bloqueo de juegos
        if not is_allowed:
            for domain in domains:
                user_rules.append(f"||{domain}^$client='{ip_addr}'")

    # Escribir las reglas en AdGuard Home (intenta primero por API y si requiere login escribe directo a AdGuardHome.yaml)
    rules_written = False
    try:
        rules_text = "\n".join(user_rules)
        req = urllib.request.Request(
            f"{ADGUARD_API_URL}/filtering/set_rules",
            data=json.dumps({"rules": rules_text}).encode('utf-8'),
            headers={'Content-Type': 'application/json'},
            method='POST'
        )
        with urllib.request.urlopen(req, timeout=5) as resp:
            rules_written = True
            log_msg("Reglas de juegos sincronizadas con AdGuard Home API exitosamente (0 ms).")
    except Exception as e:
        log_msg(f"API HTTP 401/Auth ({e}). Escribiendo reglas directamente en la configuración local de AdGuard Home...")

    if not rules_written:
        # Fallback de alta confiabilidad: Escribir reglas en AdGuardHome.yaml de OPNsense
        for yaml_path in [
            '/usr/local/bin/AdGuardHome.yaml',
            '/var/db/adguardhome/AdGuardHome.yaml',
            '/usr/local/etc/adguardhome/AdGuardHome.yaml',
            '/var/adguardhome/AdGuardHome.yaml'
        ]:
            if os.path.exists(yaml_path):
                try:
                    with open(yaml_path, 'r') as f:
                        content = f.read()
                    
                    # Formatear las reglas en la estructura YAML requerida por AdGuard Home
                    formatted_rules = "user_rules:\n" + "\n".join([f'  - "{r}"' for r in user_rules]) + "\n"
                    
                    if 'user_rules:' in content:
                        import re
                        # Reemplazar la sección user_rules completa hasta la siguiente clave principal
                        new_content = re.sub(r'user_rules:.*?(?=\n\w|\Z)', formatted_rules.strip(), content, flags=re.DOTALL)
                    else:
                        new_content = content + "\n" + formatted_rules

                    with open(yaml_path, 'w') as f:
                        f.write(new_content)
                    
                    log_msg(f"Reglas actualizadas directamente en {yaml_path}. Recargando AdGuard Home...")
                    os.system('/usr/local/bin/AdGuardHome -s restart >/dev/null 2>&1 || service adguardhome restart >/dev/null 2>&1 || pkill -HUP AdGuardHome >/dev/null 2>&1')
                    rules_written = True
                    break

                except Exception as ex:
                    log_msg(f"Error escribiendo en {yaml_path}: {ex}")



if __name__ == '__main__':
    update_game_control()








